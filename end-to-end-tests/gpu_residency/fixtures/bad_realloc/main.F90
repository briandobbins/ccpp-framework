program test_gpu_residency

  ! End-to-end test for GPU data movement generated by capgen
  ! (doc/gpu_data_movement_plan.md).  Runs three time steps of a two-group
  ! suite in column chunks, with host code changing data between the
  ! groups, and writes every final field value to gpu_residency_out.txt.
  ! The same source is built for CPU and GPU; the outputs must agree.
  !
  ! Build with -DNO_DEVICE_SYNC when the caps were generated without
  ! --directive (the sync entry points do not exist then).

  use, intrinsic :: iso_fortran_env, only: error_unit
  use ccpp_kinds, only: kind_phys
  use gpu_data, only: ncols, pver, nchunks, chunk_begin, chunk_end, &
                      temp, qv, extra, phys_state, &
                      gpu_data_alloc, gpu_data_dealloc
  use test_host_ccpp_cap, only: ccpp_register, ccpp_init, &
      ccpp_physics_init, ccpp_physics_timestep_init, ccpp_physics_run, &
      ccpp_physics_timestep_final, ccpp_physics_final, ccpp_final
#ifndef NO_DEVICE_SYNC
  use test_host_ccpp_cap, only: ccpp_physics_device_update_device, &
      ccpp_physics_device_update_host
#endif

  implicit none

  character(len=*), parameter :: suite = 'gpu_residency_suite'
  integer, parameter :: nsteps = 3
  integer :: i, k, step, ic, errflg, unit
  character(len=512) :: errmsg

  call gpu_data_alloc()
  do k = 1, pver
    do i = 1, ncols
      temp(i,k)  = 250.0_kind_phys + real(i, kind_phys) + 2.0_kind_phys*real(k, kind_phys)
      qv(i,k)    = 1.0e-3_kind_phys*(1.0_kind_phys + 0.01_kind_phys*real(i, kind_phys) &
                                     + 0.1_kind_phys*real(k, kind_phys))
      extra(i,k) = 0.1_kind_phys*real(k, kind_phys)
    end do
  end do
  do i = 1, ncols
    phys_state%ps(i)    = 1.0e5_kind_phys + 10.0_kind_phys*real(i, kind_phys)
    phys_state%precl(i) = 0.0_kind_phys
  end do

  call ccpp_register(suite_name=suite, errmsg=errmsg, errflg=errflg)
  call check('ccpp_register')
  call ccpp_init(suite_name=suite, errmsg=errmsg, errflg=errflg)
  call check('ccpp_init')
#ifndef NO_DEVICE_SYNC
  ! The device copies now exist; give them the host's initial values.
  ! Required for host_access = none variables (qv), whose valid copy
  ! lives on the device from here on.
  call ccpp_physics_device_update_device(suite_name=suite, errmsg=errmsg, errflg=errflg)
  call check('ccpp_physics_device_update_device')
#endif
  ! BUG (fixture bad_realloc): the host reallocates temp after ccpp_init
  ! created its device copy.  The device copy no longer matches the host
  ! array, so the first GPU access to temp fails.
  block
    ! Allocate the new storage while the old still exists, so it is
    ! guaranteed to live at a different address, then move it into temp.
    real(kind_phys), allocatable :: fresh(:,:)
    allocate(fresh(ncols, pver))
    fresh = temp
    call move_alloc(fresh, temp)
  end block
  call ccpp_physics_init(suite_name=suite, group_name='all', lb=1, ub=ncols, &
       thread_num=1, nthreads=1, nphys_threads=1, errmsg=errmsg, errflg=errflg)
  call check('ccpp_physics_init')

  do step = 1, nsteps
    call ccpp_physics_timestep_init(suite_name=suite, group_name='all', lb=1, ub=ncols, &
         thread_num=1, nthreads=1, nphys_threads=1, errmsg=errmsg, errflg=errflg)
    call check('ccpp_physics_timestep_init')

    do ic = 1, nchunks
      call ccpp_physics_run(suite_name=suite, group_name='before', &
           lb=chunk_begin(ic), ub=chunk_end(ic), thread_num=1, nthreads=1, &
           nphys_threads=1, errmsg=errmsg, errflg=errflg)
      call check('ccpp_physics_run(before)')
    end do

    ! Host code between the groups (a stand-in for the coupler): reads the
    ! precipitation and changes temperature (host_access = read_write).
    do k = 1, pver
      do i = 1, ncols
        temp(i,k) = temp(i,k) - 50.0_kind_phys*phys_state%precl(i)
      end do
    end do

    do ic = 1, nchunks
      call ccpp_physics_run(suite_name=suite, group_name='after', &
           lb=chunk_begin(ic), ub=chunk_end(ic), thread_num=1, nthreads=1, &
           nphys_threads=1, errmsg=errmsg, errflg=errflg)
      call check('ccpp_physics_run(after)')
    end do

    call ccpp_physics_timestep_final(suite_name=suite, group_name='all', lb=1, ub=ncols, &
         thread_num=1, nthreads=1, nphys_threads=1, errmsg=errmsg, errflg=errflg)
    call check('ccpp_physics_timestep_final')
  end do

#ifndef NO_DEVICE_SYNC
  ! Bring device-resident data (qv) back before reading it on the host.
  call ccpp_physics_device_update_host(suite_name=suite, errmsg=errmsg, errflg=errflg)
  call check('ccpp_physics_device_update_host')
#endif

  open(newunit=unit, file='gpu_residency_out.txt', status='replace', action='write')
  do k = 1, pver
    do i = 1, ncols
      write(unit, '(a,2i4,3es26.17)') 'tq', i, k, temp(i,k), qv(i,k), extra(i,k)
    end do
  end do
  do i = 1, ncols
    write(unit, '(a,i4,4x,2es26.17)') 'pp', i, phys_state%ps(i), phys_state%precl(i)
  end do
  close(unit)
  write(*, '(a,3es24.15)') 'checksums temp qv precl:', sum(temp), sum(qv), &
       sum(phys_state%precl)

  call ccpp_physics_final(suite_name=suite, group_name='all', lb=1, ub=ncols, &
       thread_num=1, nthreads=1, nphys_threads=1, errmsg=errmsg, errflg=errflg)
  call check('ccpp_physics_final')
  call ccpp_final(suite_name=suite, errmsg=errmsg, errflg=errflg)
  call check('ccpp_final')
  call gpu_data_dealloc()
  write(*, '(a)') 'test_gpu_residency: completed'

contains

  subroutine check(where)
    character(len=*), intent(in) :: where
    if (errflg /= 0) then
      write(error_unit, '(a)') 'Error in '//where//': '//trim(errmsg)
      stop 1
    end if
  end subroutine check

end program test_gpu_residency
